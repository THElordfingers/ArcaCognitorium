"""


MUNDANA STATE BUS
════════════════════════════════════════════════════════════════════════════════
Arca Cognitorium — Aggregation Layer for All Seven Machinae

Instantiates and updates all seven Machinae. Produces two output tracks:

  bus.cosmetic   — palette keys, saturation, visual intensity for UI
  bus.behaviour  — per-entity weights, global potency, trigger log

All engines share a single update loop. The Bus handles rate-limiting —
each engine updates at its own cadence. Callers just call bus.update().

Usage:
    from machinae.mundana_state_bus import MundanaStateBus

    bus = MundanaStateBus(lat=48.4, lon=-123.3, utc_offset=-8)
    bus.update()

    # Cosmetic track
    bus.cosmetic.palette_key       # "autumn"
    bus.cosmetic.saturation        # 0.68
    bus.cosmetic.intensity         # 0.0–1.0 overall visual intensity
    bus.cosmetic.storm_active      # bool — weather-driven UI effect flag

    # Behaviour track
    bus.behaviour.entity_weight("archivist")   # composite multiplier 0.5–1.5
    bus.behaviour.potency                       # 0.0–1.0 global potency
    bus.behaviour.disruptive                    # bool — entities agitated
    bus.behaviour.auspicious                    # bool

    # Raw machinae available directly
    bus.sky     # MachinaHorologica
    bus.cael    # MachinaCaelestis
    bus.circ    # MachinaCircadiana
    bus.sol     # MachinaSolaris
    bus.tidal   # MachinaTidalis
    bus.wx      # MachinaMeteorologica

    # All triggers since last poll (across all seven engines)
    bus.poll_triggers()   # list of (source, event) tuples

    # State I/O
    bus.to_json()
    bus.write()     # writes ~/.arca/mundana_state.json

════════════════════════════════════════════════════════════════════════════════
"""

