class MundanaStateBus:
    """
    Aggregation layer for all seven Machinae.

    bus = MundanaStateBus(lat=48.4, lon=-123.3, utc_offset=-8)
    bus.update()

    bus.cosmetic.palette_key
    bus.behaviour.entity_weight("archivist")
    bus.poll_triggers()
    bus.write()
    """

    def __init__(self,
                 lat:        float = 48.4,
                 lon:        float = -123.3,
                 utc_offset: float = -8.0):

        self.lat        = lat
        self.lon        = lon
        self.utc_offset = utc_offset

        # Import all machinae — fail loudly if missing
        from machinae.machina_horologica    import MachinaHorologica
        from machinae.machina_caelestis     import MachinaCaelestis
        from machinae.machina_circadiana    import MachinaCircadiana
        from machinae.machina_solaris       import MachinaSolaris
        from machinae.machina_tidalis       import MachinaTidalis
        from machinae.machina_meteorologica import MachinaMeteorologica

        self.sky   = MachinaHorologica()
        self.cael  = MachinaCaelestis()
        self.circ  = MachinaCircadiana(utc_offset_hours=utc_offset)
        self.sol   = MachinaSolaris()
        self.tidal = MachinaTidalis(lat=lat, lon=lon)
        self.wx    = MachinaMeteorologica(lat=lat, lon=lon)

        self.cosmetic  = CosmeticTrack()
        self.behaviour = BehaviourTrack()

        self._tick  = 0
        self._cycle = 0

    def update(self, force: bool = False):
        """
        Update all seven machinae and regenerate both output tracks.
        Call every second from the Tower's main loop.
        Each engine rate-limits its own heavy work internally.
        """
        self._tick += 1

        # Update all engines — each rate-limits heavy work internally
        self.sky.update(force=force)
        self.cael.update(self.sky, force=force)
        self.circ.update()
        self.sol.update()
        self.tidal.update()
        self.wx.update()

        # Regenerate output tracks every tick (cheap reads from updated state)
        self.cosmetic.update(
            self.sky, self.cael, self.circ, self.sol, self.tidal, self.wx)
        self.behaviour.update(
            self.sky, self.cael, self.circ, self.sol, self.tidal, self.wx)

        self._cycle += 1

    def poll_triggers(self) -> list:
        """
        Drain all pending triggers from all seven engines.
        Returns list of (source, event) tuples.
        """
        triggers = []
        triggers += [("sky",   e) for e in self.sky.triggers.poll()]
        triggers += [("cael",  e) for e in self.cael.triggers.poll()]
        triggers += [("circ",  e) for e in self.circ.triggers.poll()]
        triggers += [("sol",   e) for e in self.sol.triggers.poll()]
        triggers += [("tidal", e) for e in self.tidal.triggers.poll()]
        triggers += [("wx",    e) for e in self.wx.triggers.poll()]
        return triggers

    def summary(self) -> str:
        return (
            f"potency:{self.behaviour.potency:.2f}  "
            f"palette:{self.cosmetic.palette_key:<8}  "
            f"sat:{self.cosmetic.saturation:.2f}  "
            f"intensity:{self.cosmetic.intensity:.2f}  "
            f"dasha:{self.behaviour.dasha_planet:<10}  "
            f"{'DISRUPTIVE' if self.behaviour.disruptive else 'stable'}"
        )

    def to_dict(self) -> dict:
        return {
            "meta": {
                "ts":      datetime.now(timezone.utc).isoformat(),
                "version": VERSION,
                "tick":    self._tick,
                "cycle":   self._cycle,
                "lat":     self.lat,
                "lon":     self.lon,
            },
            "cosmetic":  self.cosmetic.to_dict(),
            "behaviour": self.behaviour.to_dict(),
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, default=str)

    def write(self):
        """Atomic write to ~/.arca/mundana_state.json"""
        ARCA_DIR.mkdir(exist_ok=True)
        tmp = ARCA_DIR / "mundana_state.tmp"
        with open(tmp, "w") as f:
            f.write(self.to_json())
        tmp.replace(STATE_PATH)


