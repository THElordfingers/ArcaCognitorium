def run_daemon(lat: float, lon: float, utc_offset: float):
    bus = MundanaStateBus(lat=lat, lon=lon, utc_offset=utc_offset)
    print(f"MUNDANA STATE BUS  v{VERSION}")
    print(f"Writing to: {STATE_PATH}")
    print(f"Location: {lat}, {lon}  UTC{utc_offset:+.1f}")
    print("Ctrl+C to stop.\n")
    try:
        while True:
            bus.update()
            bus.write()
            triggers = bus.poll_triggers()
            if triggers:
                ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
                for source, event in triggers:
                    print(f"  [{ts}] {source.upper():<5} TRIGGER: {event}")
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nDaemon stopped.")


def run_once(lat: float, lon: float, utc_offset: float):
    bus = MundanaStateBus(lat=lat, lon=lon, utc_offset=utc_offset)
    bus.update(force=True)
    bus.write()
    print(bus.to_json())


def run_watch(lat: float, lon: float, utc_offset: float):
    bus = MundanaStateBus(lat=lat, lon=lon, utc_offset=utc_offset)
    try:
        while True:
            bus.update()
            bus.write()
            os.system("clear")
            print(f"  MUNDANA STATE BUS  v{VERSION}")
            print(f"  {bus.summary()}")
            print()
            print(f"  COSMETIC TRACK")
            for k, v in bus.cosmetic.to_dict().items():
                print(f"    {k:<22} {v}")
            print()
            print(f"  BEHAVIOUR TRACK")
            print(f"    potency:         {bus.behaviour.potency:.3f}")
            print(f"    auspicious:      {bus.behaviour.auspicious}")
            print(f"    disruptive:      {bus.behaviour.disruptive}")
            print(f"    mercury_rx:      {bus.behaviour.mercury_rx}")
            print(f"    dasha:           {bus.behaviour.dasha_planet}")
            print(f"    council_coh:     {bus.behaviour.council_coherence:.3f}")
            print()
            print(f"  ENTITY WEIGHTS")
            for entity, w in sorted(bus.behaviour.all_weights().items()):
                bar_len = int((w - 0.5) * 30)
                bar = ("▮" * max(0, bar_len)) if w >= 1.0 else ("▯" * max(0, -bar_len))
                print(f"    {entity:<18} {w:.4f}  {bar}")
            triggers = bus.poll_triggers()
            if triggers:
                print()
                print(f"  TRIGGERS")
                for source, event in triggers:
                    print(f"    [{source:<5}] {event}")
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nWatch stopped.")


def _parse_args(args):
    lat, lon, utc = 48.4, -123.3, -8.0
    for i, a in enumerate(args):
        if a == "--lat"    and i + 1 < len(args): lat = float(args[i+1])
        if a == "--lon"    and i + 1 < len(args): lon = float(args[i+1])
        if a == "--utc"    and i + 1 < len(args): utc = float(args[i+1])
    return lat, lon, utc


if __name__ == "__main__":
    args = sys.argv[1:]
    lat, lon, utc = _parse_args(args)
    if "--once"  in args: run_once(lat, lon, utc)
    elif "--watch" in args: run_watch(lat, lon, utc)
    else: run_daemon(lat, lon, utc)

