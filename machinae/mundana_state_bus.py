class CosmeticTrack:
    """
    Visual signals for the Tower UI.
    Updated from all seven machinae. Consumed by palette system,
    animations, and ambient visual effects.
    """
    def __init__(self):
        self.palette_key      = "neutral"    # "winter"/"spring"/"summer"/"autumn"/"storm"/"eclipse"
        self.saturation       = 0.68         # 0.4–1.0 — modulates palette vibrancy
        self.intensity        = 0.50         # 0.0–1.0 — overall visual intensity
        self.storm_active     = False        # weather UI effect
        self.eclipse_active   = False        # eclipse UI effect
        self.full_moon_active = False        # full moon UI effect
        self.mercury_rx       = False        # Mercury rx UI effect
        self.solar_storm      = False        # geomagnetic storm UI effect
        self.tidal_peak       = False        # spring tide / perigee visual
        self.is_day           = True         # day/night UI mode

    def update(self, sky, cael, circ, sol, tidal, wx):
        # Palette — season base, overridden by dramatic weather
        self.palette_key = sky.season.palette_key
        if wx.conditions.stormy:
            self.palette_key = "storm"
        if sky.conditions.eclipse_active:
            self.palette_key = "eclipse"

        # Saturation — lunar modulation from Horologica
        self.saturation       = sky.season.saturation

        # Boolean effect flags
        self.storm_active     = wx.conditions.stormy
        self.eclipse_active   = sky.conditions.eclipse_active
        self.full_moon_active = sky.conditions.moon_full
        self.mercury_rx       = sky.conditions.mercury_rx
        self.solar_storm      = sol.kp.storm_active
        self.tidal_peak       = tidal.conditions.peak_tidal
        self.is_day           = wx.current.is_day

        # Intensity — composite of all dramatic factors
        score = 0.40
        score += (sky.moon.illumination / 100) * 0.20
        score += cael.conditions.potency            * 0.20
        score += sol.conditions.potency             * 0.10
        score += tidal.conditions.potency           * 0.05
        score += wx.conditions.potency              * 0.05
        if self.eclipse_active:   score += 0.15
        if self.solar_storm:      score += 0.10
        if self.tidal_peak:       score += 0.05
        self.intensity = round(max(0.0, min(1.0, score)), 3)

    def to_dict(self) -> dict:
        return self.__dict__


class BehaviourTrack:
    """
    Behavioural signals for entity modulation.
    Updated from all seven machinae. Consumed by entity compiler
    and the Celestial Resolver.
    """
    def __init__(self):
        self.potency          = 0.50    # 0.0–1.0 global potency
        self.auspicious       = True    # from sky panchang
        self.disruptive       = False   # sol storm or extreme tidal or stormy wx
        self.mercury_rx       = False
        self.eclipse_active   = False
        self.rahu_kalam       = False
        self.dasha_planet     = "Ketu"
        self.dasha_benefic    = True
        self.council_coherence= 0.5     # from MachinaCircadiana
        self._entity_weights  : dict = {}

    def update(self, sky, cael, circ, sol, tidal, wx):
        self.auspicious        = sky.conditions.auspicious
        self.mercury_rx        = sky.conditions.mercury_rx
        self.eclipse_active    = sky.conditions.eclipse_active
        self.rahu_kalam        = sky.conditions.rahu_kalam_now
        self.dasha_planet      = cael.dasha.maha_dasha
        self.dasha_benefic     = cael.conditions.dasha_benefic
        self.council_coherence = circ.conditions.council_coherence
        self.disruptive        = (
            sol.conditions.disruptive or
            tidal.conditions.peak_tidal or
            wx.conditions.stormy
        )

        # Composite potency — weighted average of all engine potencies
        self.potency = round(
            sky.conditions.potency   * 0.30 +
            cael.conditions.potency  * 0.25 +
            circ.conditions.average_position * 0.20 +
            sol.conditions.potency   * 0.10 +
            tidal.conditions.potency * 0.08 +
            wx.conditions.potency    * 0.07,
        3)

        # Per-entity composite weights
        for entity in _ENTITY_NAMES:
            sky_aff  = sky.entities.get(entity)       # float, ~0.5–1.5
            circ_w   = circ.entity_weight(entity)      # float, 0.5–1.5
            sol_mod  = 1.0 - sol.conditions.potency * 0.08
            tidal_mod= 1.0 + (tidal.combined.force - 1.0) * 0.04
            cael_mod = cael.conditions.potency * 0.10 + 0.95  # slight boost when sky is high quality

            # Default blend — can be overridden by celestial.yaml via resolver
            weight = round(
                sky_aff  * 0.40 +
                circ_w   * 0.40 +
                sol_mod  * 0.10 +
                tidal_mod* 0.10,
            4)
            self._entity_weights[entity] = max(0.1, min(2.0, weight))

    def entity_weight(self, entity: str) -> float:
        return self._entity_weights.get(entity, 1.0)

    def all_weights(self) -> dict:
        return dict(self._entity_weights)

    def to_dict(self) -> dict:
        return {
            "potency":           self.potency,
            "auspicious":        self.auspicious,
            "disruptive":        self.disruptive,
            "mercury_rx":        self.mercury_rx,
            "eclipse_active":    self.eclipse_active,
            "rahu_kalam":        self.rahu_kalam,
            "dasha_planet":      self.dasha_planet,
            "dasha_benefic":     self.dasha_benefic,
            "council_coherence": self.council_coherence,
            "entity_weights":    self._entity_weights,
        }


