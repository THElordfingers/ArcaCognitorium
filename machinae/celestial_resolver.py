def _load_celestial_yaml(entity_id: str) -> Optional[dict]:
    """
    Load celestial.yaml for an entity.
    Returns dict on success, None if file absent or yaml unavailable.
    """
    path = ENTITY_STORAGE / entity_id / "celestial.yaml"
    if not path.exists():
        return None
    if not _YAML_AVAILABLE:
        # Fallback: attempt basic key:value parse without PyYAML
        return _parse_yaml_fallback(path)
    try:
        with path.open() as f:
            return yaml.safe_load(f)
    except Exception:
        return None


def _parse_yaml_fallback(path: Path) -> dict:
    """
    Minimal YAML parser for simple flat key: value pairs and lists.
    Handles the celestial.yaml structure without PyYAML dependency.
    """
    data: dict = {}
    try:
        lines = path.read_text().splitlines()
        current_key = None
        current_list = None
        for raw_line in lines:
            line = raw_line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("- "):
                val = line[2:].strip()
                # Try numeric
                try:
                    val = float(val) if "." in val else int(val)
                except ValueError:
                    pass
                if current_list is not None:
                    current_list.append(val)
                continue
            if ":" in line:
                key, _, rest = line.partition(":")
                key  = key.strip()
                rest = rest.strip()
                if rest == "":
                    # Block scalar (list follows)
                    current_list = []
                    data[key]    = current_list
                    current_key  = key
                else:
                    current_list = None
                    current_key  = key
                    # Try numeric
                    try:
                        rest = float(rest) if "." in rest else int(rest)
                    except ValueError:
                        # Try bool
                        if rest.lower() == "true":  rest = True
                        elif rest.lower() == "false": rest = False
                    data[key] = rest
    except Exception:
        pass
    return data


