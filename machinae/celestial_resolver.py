class CelestialResolver:
    """
    Per-entity CelestialContext injection from Mundana State Bus.

    resolver = CelestialResolver()
    bus.update()
    resolver.update(bus)
    ctx = resolver.get("archivist")
    """

    def __init__(self):
        self._contexts : dict[str, CelestialContext] = {
            e: CelestialContext(e) for e in ENTITY_NAMES
        }
        self._yamls    : dict[str, Optional[dict]] = {}
        self._yaml_mtime: dict[str, float] = {}
        self._tick     = 0
        self._last_yaml_check = 0.0

        # Load yamls on init
        self._reload_yamls()

    def _reload_yamls(self):
        """Reload any celestial.yaml files that have changed on disk."""
        for entity_id in ENTITY_NAMES:
            path  = ENTITY_STORAGE / entity_id / "celestial.yaml"
            mtime = path.stat().st_mtime if path.exists() else 0.0
            if self._yaml_mtime.get(entity_id, -1) != mtime:
                self._yamls[entity_id]     = _load_celestial_yaml(entity_id)
                self._yaml_mtime[entity_id] = mtime

    def update(self, bus, force: bool = False):
        """
        Resolve all entity contexts from current bus state.
        Reloads changed celestial.yaml files every 60s.
        """
        self._tick += 1

        if force or (time.time() - self._last_yaml_check >= 60):
            self._reload_yamls()
            self._last_yaml_check = time.time()

        for entity_id in ENTITY_NAMES:
            cfg = self._yamls.get(entity_id)
            self._contexts[entity_id] = _resolve_entity(entity_id, bus, cfg)

    def get(self, entity_id: str) -> CelestialContext:
        return self._contexts.get(entity_id, CelestialContext(entity_id))

    def all(self) -> dict[str, CelestialContext]:
        return dict(self._contexts)

    def weights(self) -> dict[str, float]:
        return {e: ctx.weight for e, ctx in self._contexts.items()}

    def to_dict(self) -> dict:
        return {
            "meta": {
                "ts":      datetime.now(timezone.utc).isoformat(),
                "version": VERSION,
                "tick":    self._tick,
            },
            "entities": {e: ctx.to_dict() for e, ctx in self._contexts.items()},
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, default=str)

    def write(self):
        """Atomic write to ~/.arca/celestial_resolver.json"""
        ARCA_DIR.mkdir(exist_ok=True)
        tmp = ARCA_DIR / "celestial_resolver.tmp"
        with open(tmp, "w") as f:
            f.write(self.to_json())
        tmp.replace(STATE_PATH)


# ─────────────────────────────────────────────────────────────────────────────
# DAEMON / CLI  (requires MundanaStateBus)
# ─────────────────────────────────────────────────────────────────────────────

def _make_bus_and_resolver(lat, lon, utc):
    from machinae.mundana_state_bus import MundanaStateBus
    return MundanaStateBus(lat=lat, lon=lon, utc_offset=utc), CelestialResolver()


def run_daemon(lat, lon, utc):
    bus, resolver = _make_bus_and_resolver(lat, lon, utc)
    print(f"CELESTIAL RESOLVER  v{VERSION}")
    print(f"Writing to: {STATE_PATH}")
    print("Ctrl+C to stop.\n")
    try:
        while True:
            bus.update()
            resolver.update(bus)
            resolver.write()
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nDaemon stopped.")


def run_once(lat, lon, utc):
    bus, resolver = _make_bus_and_resolver(lat, lon, utc)
    bus.update(force=True)
    resolver.update(bus, force=True)
    resolver.write()
    print(resolver.to_json())


def run_watch(lat, lon, utc):
    bus, resolver = _make_bus_and_resolver(lat, lon, utc)
    try:
        while True:
            bus.update()
            resolver.update(bus)
            resolver.write()
            os.system("clear")
            print(f"  CELESTIAL RESOLVER  v{VERSION}")
            print()
            for entity_id in ENTITY_NAMES:
                ctx = resolver.get(entity_id)
                yaml_marker = "✦" if ctx.yaml_loaded else "·"
                bar_len = int((ctx.weight - 0.5) * 30)
                bar = ("▮" * max(0, bar_len)) if ctx.weight >= 1.0 else ("▯" * max(0, -bar_len))
                print(f"  {yaml_marker} {entity_id:<18} {ctx.weight:.4f}  {bar}")
                if ctx.affinities or ctx.resistances or ctx.special_conditions:
                    if ctx.affinities:
                        print(f"      aff:  {', '.join(ctx.affinities)}")
                    if ctx.resistances:
                        print(f"      res:  {', '.join(ctx.resistances)}")
                    if ctx.vulnerabilities:
                        print(f"      vuln: {', '.join(ctx.vulnerabilities)}")
                    if ctx.special_conditions:
                        print(f"      ★     {'; '.join(ctx.special_conditions)}")
            print()
            print(f"  bus potency: {bus.behaviour.potency:.3f}  "
                  f"dasha: {bus.behaviour.dasha_planet}  "
                  f"palette: {bus.cosmetic.palette_key}")
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nWatch stopped.")


def _parse_args(args):
    lat, lon, utc = 48.4, -123.3, -8.0
    for i, a in enumerate(args):
        if a == "--lat" and i + 1 < len(args): lat = float(args[i+1])
        if a == "--lon" and i + 1 < len(args): lon = float(args[i+1])
        if a == "--utc" and i + 1 < len(args): utc = float(args[i+1])
    return lat, lon, utc


if __name__ == "__main__":
    args = sys.argv[1:]
    lat, lon, utc = _parse_args(args)
    if "--once"    in args: run_once(lat, lon, utc)
    elif "--watch" in args: run_watch(lat, lon, utc)
    else: run_daemon(lat, lon, utc)

