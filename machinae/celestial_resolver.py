def _resolve_entity(entity_id: str, bus, cfg: Optional[dict]) -> CelestialContext:
    """
    Resolve a CelestialContext for a single entity.
    Uses cfg (celestial.yaml dict) when present, falls back to bus defaults.
    """
    ctx = CelestialContext(entity_id)
    ctx.yaml_loaded = cfg is not None

    # ── Weight calculation ───────────────────────────────────────────────────

    # Base weight from bus behaviour track (already composite)
    base_weight = bus.behaviour.entity_weight(entity_id)

    if cfg:
        # Per-entity weight blending coefficients from yaml
        circ_w   = float(cfg.get("circadian_weight",  0.40))
        cael_w   = float(cfg.get("celestial_weight",  0.40))
        sol_w    = float(cfg.get("solar_weight",       0.10))
        tidal_w  = float(cfg.get("tidal_weight",       0.10))

        sky_aff  = bus.sky.entities.get(entity_id)
        circ_pos = bus.circ.entity_weight(entity_id)
        sol_mod  = 1.0 - bus.sol.conditions.potency   * 0.08
        tidal_mod= 1.0 + (bus.tidal.combined.force - 1.0) * 0.04

        base_weight = round(
            sky_aff   * cael_w  +
            circ_pos  * circ_w  +
            sol_mod   * sol_w   +
            tidal_mod * tidal_w,
        4)

        # Dasha affinity bonus/penalty
        dasha_affinities = cfg.get("dasha_affinities", {})
        dasha_planet = bus.cael.dasha.maha_dasha
        if isinstance(dasha_affinities, dict) and dasha_planet in dasha_affinities:
            base_weight += float(dasha_affinities[dasha_planet])

    weight = base_weight

    # ── Active condition flags ───────────────────────────────────────────────
    sky   = bus.sky
    cael  = bus.cael
    circ  = bus.circ
    sol   = bus.sol
    tidal = bus.tidal
    wx    = bus.wx

    # Build the live condition set — names that can match yaml lists
    active_conditions: set = set()
    if sky.conditions.mercury_rx:          active_conditions.add("mercury_rx")
    if sky.conditions.eclipse_active:      active_conditions.add("eclipse_season")
    if sky.conditions.moon_full:           active_conditions.add("full_moon")
    if sky.conditions.moon_new:            active_conditions.add("new_moon")
    if sky.conditions.moon_supermoon:      active_conditions.add("supermoon")
    if sky.conditions.venus_rx:            active_conditions.add("venus_rx")
    if sky.conditions.mars_rx:             active_conditions.add("mars_rx")
    if sky.conditions.saturn_rx:           active_conditions.add("saturn_rx")
    if sky.conditions.rahu_kalam_now:      active_conditions.add("rahu_kalam")
    if sky.conditions.auspicious:          active_conditions.add("auspicious")
    if not sky.conditions.auspicious:      active_conditions.add("inauspicious")
    if sol.conditions.disruptive:          active_conditions.add("solar_storm")
    if sol.conditions.quiet:               active_conditions.add("solar_quiet")
    if tidal.conditions.peak_tidal:        active_conditions.add("peak_tidal")
    if tidal.conditions.spring_tide:       active_conditions.add("spring_tide")
    if tidal.conditions.neap_tide:         active_conditions.add("neap_tide")
    if wx.conditions.stormy:               active_conditions.add("storm")
    if wx.conditions.serene:               active_conditions.add("serene")
    if wx.conditions.oppressive:           active_conditions.add("oppressive")

    # Circadian state — entity-specific
    if entity_id in circ.entities:
        if circ.entities[entity_id].peak:    active_conditions.add("circadian_peak")
        if circ.entities[entity_id].trough:  active_conditions.add("circadian_trough")

    # Sun sign as condition key (e.g. "sun_virgo")
    sun_sign_cond = f"solar_ingress:{sky.sun.sign_name}"
    active_conditions.add(sun_sign_cond)

    # Dasha as condition
    active_conditions.add(f"dasha:{cael.dasha.maha_dasha}")
    active_conditions.add(f"antar:{cael.dasha.antar_dasha}")

    # Dignity of entity's affinity planets (if yaml defined)
    if cfg:
        for planet in cfg.get("affinity_planets", []):
            planet = str(planet)
            if planet in cael.dignities._planets:
                dig_status = cael.dignities[planet].status
                active_conditions.add(f"dignity:{planet}:{dig_status}")

    # ── YAML-driven condition matching ───────────────────────────────────────

    if cfg:
        # Affinities
        for cond in cfg.get("affinity_signs", []):
            # sign index matching — convert to sign name check
            pass  # handled by sky.entities already

        for cond in cfg.get("vulnerability_conditions", []):
            cond = str(cond)
            if cond in active_conditions:
                ctx.vulnerabilities.append(cond)

        # Special alignments — named events with weight bonus
        for alignment in cfg.get("special_alignments", []):
            if not isinstance(alignment, dict):
                continue
            condition = str(alignment.get("condition", ""))
            label     = str(alignment.get("label", condition))
            bonus     = float(alignment.get("weight_bonus", 0.0))
            if condition in active_conditions:
                ctx.special_conditions.append(label)
                weight += bonus

        # Affinity conditions from yaml free list
        for cond in cfg.get("affinity_conditions", []):
            cond = str(cond)
            if cond in active_conditions:
                ctx.affinities.append(cond)
                weight += 0.08

        # Resistance conditions
        for cond in cfg.get("resistance_conditions", []):
            cond = str(cond)
            if cond in active_conditions:
                ctx.resistances.append(cond)
                weight -= 0.08

        # Affinity tithis
        current_tithi = sky.panchang.tithi_name
        for t in cfg.get("affinity_tithis", []):
            if str(t) == current_tithi:
                ctx.affinities.append(f"tithi:{current_tithi}")
                weight += 0.06

        # Nakshatra affinities
        current_nak = sky.moon.nakshatra_name
        for n in cfg.get("affinity_nakshatras", []):
            if str(n) == current_nak:
                ctx.affinities.append(f"nakshatra:{current_nak}")
                weight += 0.10

    else:
        # No yaml — derive basic affinities from active conditions and bus state
        if "full_moon"      in active_conditions: ctx.affinities.append("full_moon")
        if "auspicious"     in active_conditions: ctx.affinities.append("auspicious")
        if "solar_quiet"    in active_conditions: ctx.affinities.append("solar_quiet")
        if "serene"         in active_conditions: ctx.affinities.append("serene")
        if "solar_storm"    in active_conditions: ctx.resistances.append("solar_storm")
        if "inauspicious"   in active_conditions: ctx.resistances.append("inauspicious")
        if "mercury_rx"     in active_conditions: ctx.resistances.append("mercury_rx")

    # ── Cross-condition special detections ──────────────────────────────────

    # Mercury rx during circadian peak — always notable regardless of yaml
    if "mercury_rx" in active_conditions and "circadian_peak" in active_conditions:
        label = f"Mercury retrograde during {entity_id} peak"
        if label not in ctx.special_conditions:
            ctx.special_conditions.append(label)

    # Eclipse during circadian trough — destabilising
    if "eclipse_season" in active_conditions and "circadian_trough" in active_conditions:
        label = f"Eclipse season while {entity_id} at trough"
        if label not in ctx.special_conditions:
            ctx.special_conditions.append(label)
            weight -= 0.10

    # ── Clamp and finalise ───────────────────────────────────────────────────

    ctx.weight = round(max(0.10, min(2.0, weight)), 4)

    parts = []
    if ctx.affinities:      parts.append(f"aff:[{','.join(ctx.affinities[:3])}]")
    if ctx.resistances:     parts.append(f"res:[{','.join(ctx.resistances[:2])}]")
    if ctx.vulnerabilities: parts.append(f"vuln:[{','.join(ctx.vulnerabilities[:2])}]")
    ctx.description = f"w:{ctx.weight:.3f}  " + "  ".join(parts) if parts else f"w:{ctx.weight:.3f}  nominal"

    return ctx


