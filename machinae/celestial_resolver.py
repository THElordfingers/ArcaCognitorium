class CelestialContext:
    """
    The resolved celestial context for a single entity.
    Produced by CelestialResolver.update() for each entity.
    """
    def __init__(self, entity_id: str):
        self.entity_id        = entity_id
        self.weight           = 1.0       # composite weight multiplier
        self.affinities       : list = [] # active conditions that amplify
        self.resistances      : list = [] # active conditions that dampen
        self.vulnerabilities  : list = [] # active conditions causing pronounced shift
        self.special_conditions:list = [] # named alignment events
        self.description      = ""
        self.yaml_loaded      = False     # whether celestial.yaml was found

    def to_dict(self) -> dict:
        return {
            "entity_id":          self.entity_id,
            "weight":             self.weight,
            "affinities":         self.affinities,
            "resistances":        self.resistances,
            "vulnerabilities":    self.vulnerabilities,
            "special_conditions": self.special_conditions,
            "description":        self.description,
            "yaml_loaded":        self.yaml_loaded,
        }


