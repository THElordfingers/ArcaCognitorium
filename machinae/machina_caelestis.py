class AspectEvent:
    """A single planetary aspect currently active."""
    def __init__(self, planet_a: str, planet_b: str, aspect_name: str,
                 orb: float, exact: bool, quality: str):
        self.planet_a    = planet_a
        self.planet_b    = planet_b
        self.aspect_name = aspect_name
        self.orb         = orb        # degrees from exactness
        self.exact       = exact      # within 1°
        self.quality     = quality    # "harmonious" / "tense" / "variable"

        # Refine conjunction quality by planet natures
        if aspect_name == "conjunction":
            a_mal = planet_a in NATURAL_MALEFICS
            b_mal = planet_b in NATURAL_MALEFICS
            if a_mal and b_mal:
                self.quality = "tense"
            elif not a_mal and not b_mal:
                self.quality = "harmonious"
            else:
                self.quality = "mixed"

    def label(self) -> str:
        return f"{self.planet_a}–{self.planet_b} {self.aspect_name} ({self.orb:.1f}°)"

    def to_dict(self) -> dict:
        return {
            "planet_a":    self.planet_a,
            "planet_b":    self.planet_b,
            "aspect_name": self.aspect_name,
            "orb":         self.orb,
            "exact":       self.exact,
            "quality":     self.quality,
            "label":       self.label(),
        }


class AspectState:
    """All active aspects between the seven classical planets."""
    def __init__(self):
        self.list:       list  = []   # [AspectEvent, ...]
        self.count:      int   = 0
        self.harmonious: int   = 0    # count of harmonious aspects
        self.tense:      int   = 0    # count of tense aspects
        self.exact_count:int   = 0    # aspects within 1°

    def update(self, longitudes: dict):
        """Recalculate all aspects from current planetary longitudes."""
        self.list = []
        planets   = list(longitudes.keys())

        for i in range(len(planets)):
            for j in range(i + 1, len(planets)):
                pa = planets[i]
                pb = planets[j]
                # Skip Node-to-Node (always opposition)
                if pa in ("Rahu", "Ketu") and pb in ("Rahu", "Ketu"):
                    continue
                diff = _angle_diff(longitudes[pa], longitudes[pb])

                for asp_name, (target, orb_max) in ASPECTS.items():
                    orb = abs(diff - target)
                    if orb <= orb_max:
                        evt = AspectEvent(
                            pa, pb, asp_name,
                            round(orb, 2),
                            orb <= 1.0,
                            ASPECT_QUALITY[asp_name],
                        )
                        self.list.append(evt)
                        break   # one aspect per pair

        self.count       = len(self.list)
        self.harmonious  = sum(1 for a in self.list if a.quality == "harmonious")
        self.tense       = sum(1 for a in self.list if a.quality in ("tense", "mixed"))
        self.exact_count = sum(1 for a in self.list if a.exact)

    def has_aspect(self, planet_a: str, planet_b: str, aspect_name: str = None) -> bool:
        for a in self.list:
            pair_match = {a.planet_a, a.planet_b} == {planet_a, planet_b}
            if pair_match and (aspect_name is None or a.aspect_name == aspect_name):
                return True
        return False

    def for_planet(self, planet: str) -> list:
        return [a for a in self.list if planet in (a.planet_a, a.planet_b)]

    def to_dict(self) -> dict:
        return {
            "count":       self.count,
            "harmonious":  self.harmonious,
            "tense":       self.tense,
            "exact_count": self.exact_count,
            "list":        [a.to_dict() for a in self.list],
        }


class DignityState:
    """Dignity of a single planet in its current sign."""
    def __init__(self, planet: str):
        self.planet      = planet
        self.sign_idx    = 0
        self.sign_name   = "Aries"
        self.status      = "neutral"   # exalted/own/neutral/enemy/debilitated
        self.strength    = 1.0         # 0.0–2.0  multiplier for entity scoring

    def update(self, planet: str, sign_idx: int):
        self.sign_idx  = sign_idx
        self.sign_name = SIGN_NAMES[sign_idx]
        data           = SIGN_DATA[sign_idx]

        if data.get("exaltation") == planet:
            self.status   = "exalted"
            self.strength = 1.75
        elif data.get("debilitation") == planet:
            self.status   = "debilitated"
            self.strength = 0.40
        elif planet in PLANET_OWN_SIGNS and sign_idx in PLANET_OWN_SIGNS.get(planet, []):
            self.status   = "own_sign"
            self.strength = 1.50
        elif planet in PLANET_ENEMY_SIGNS and sign_idx in PLANET_ENEMY_SIGNS.get(planet, []):
            self.status   = "enemy_sign"
            self.strength = 0.65
        else:
            self.status   = "neutral"
            self.strength = 1.00

    def to_dict(self) -> dict:
        return {
            "planet":   self.planet,
            "sign":     self.sign_name,
            "status":   self.status,
            "strength": self.strength,
        }


class DignityRegistry:
    """Dignity states for all seven classical planets."""
    def __init__(self):
        self._planets = {p: DignityState(p) for p in PLANET_IDS if p != "Rahu"}
        # Add Ketu
        self._planets["Ketu"] = DignityState("Ketu")

    def update(self, planet_signs: dict):
        """planet_signs: {planet_name: sign_idx}"""
        for planet, sign_idx in planet_signs.items():
            if planet in self._planets:
                self._planets[planet].update(planet, sign_idx)

    def __getitem__(self, planet: str) -> DignityState:
        return self._planets.get(planet, DignityState(planet))

    def to_dict(self) -> dict:
        return {p: d.to_dict() for p, d in self._planets.items()}

    def exalted(self) -> list:
        return [p for p, d in self._planets.items() if d.status == "exalted"]

    def debilitated(self) -> list:
        return [p for p, d in self._planets.items() if d.status == "debilitated"]

    def benefic_strength(self) -> float:
        """Mean strength of natural benefics — used in potency calculation."""
        bens = [self._planets[p].strength for p in NATURAL_BENEFICS
                if p in self._planets]
        return sum(bens) / len(bens) if bens else 1.0

    def malefic_strength(self) -> float:
        """Mean strength of natural malefics."""
        mals = [self._planets[p].strength for p in NATURAL_MALEFICS
                if p in self._planets]
        return sum(mals) / len(mals) if mals else 1.0


class DashaState:
    """
    Current Vimshottari dasha period inferred from Moon's nakshatra.
    Maha dasha = major period. Antar dasha = sub-period (approximated).

    Note: Precise dasha requires a birth date. This engine calculates the
    dasha the current Moon nakshatra implies — i.e. the collective/world
    dasha running through the sky right now, not a personal chart.
    Suitable for Tower entity modulation. Not a replacement for a natal chart.
    """
    def __init__(self):
        self.maha_dasha         = "Ketu"
        self.maha_ruler         = "Ketu"
        self.maha_years         = 7
        self.maha_elapsed_years = 0.0
        self.maha_remaining     = 7.0
        self.maha_pct           = 0.0     # 0.0–1.0 progress through maha

        self.antar_dasha        = "Ketu"  # sub-period planet
        self.antar_years        = 0.0
        self.antar_elapsed      = 0.0
        self.antar_remaining    = 0.0
        self.antar_pct          = 0.0

        self.nakshatra_idx      = 0

    def update(self, moon_lon: float):
        info = _dasha_balance_at_birth(moon_lon)
        self.maha_dasha         = info["ruler"]
        self.maha_ruler         = info["ruler"]
        self.maha_years         = info["dasha_years"]
        self.maha_elapsed_years = info["elapsed_years"]
        self.maha_remaining     = info["remaining_years"]
        self.maha_pct           = round(info["elapsed_years"] / info["dasha_years"], 4)
        self.nakshatra_idx      = info["nakshatra_idx"]

        # Antar dasha — cycle through sub-periods proportionally within maha
        # Each sub-period duration = (sub_years / 120) * maha_years
        start_planet_idx = DASHA_SEQUENCE.index(self.maha_dasha)
        elapsed = info["elapsed_years"]
        running = 0.0
        for i in range(9):
            sub_planet = DASHA_SEQUENCE[(start_planet_idx + i) % 9]
            sub_yrs    = (DASHA_YEARS[sub_planet] / TOTAL_DASHA_YEARS) * self.maha_years
            if running + sub_yrs >= elapsed:
                self.antar_dasha    = sub_planet
                self.antar_years    = round(sub_yrs, 4)
                sub_elapsed         = elapsed - running
                self.antar_elapsed  = round(sub_elapsed, 4)
                self.antar_remaining= round(sub_yrs - sub_elapsed, 4)
                self.antar_pct      = round(sub_elapsed / sub_yrs, 4) if sub_yrs > 0 else 0.0
                break
            running += sub_yrs

    def label(self) -> str:
        return f"{self.maha_dasha} / {self.antar_dasha}"

    def to_dict(self) -> dict:
        return {
            "maha_dasha":          self.maha_dasha,
            "maha_years":          self.maha_years,
            "maha_elapsed_years":  self.maha_elapsed_years,
            "maha_remaining":      self.maha_remaining,
            "maha_pct":            self.maha_pct,
            "antar_dasha":         self.antar_dasha,
            "antar_years":         self.antar_years,
            "antar_elapsed":       self.antar_elapsed,
            "antar_remaining":     self.antar_remaining,
            "antar_pct":           self.antar_pct,
            "nakshatra_idx":       self.nakshatra_idx,
            "label":               self.label(),
        }


class CaelestisConditions:
    """
    Composite astrological quality — synthesised from aspects, dignities, dasha.
    potency: 0.0–1.0 overall astrological intensity/quality.
    """
    def __init__(self):
        self.potency          = 0.5
        self.quality          = "neutral"     # "auspicious" / "neutral" / "challenging"
        self.aspect_harmony   = 0.5           # 0.0–1.0 balance of harmonious vs tense
        self.dignity_score    = 1.0           # mean dignity strength across benefics
        self.dasha_benefic    = True          # is current maha dasha a natural benefic?
        self.dasha_planet     = "Ketu"
        self.description      = ""
        self.exalted_planets  : list = []
        self.debilitated_planets: list = []
        self.active_aspects   : int  = 0
        self.exact_aspects    : int  = 0

    def update(self, aspects: AspectState, dignities: DignityRegistry,
               dasha: DashaState):

        # Aspect harmony score
        total_asp = aspects.count or 1
        harm_ratio = aspects.harmonious / total_asp
        self.aspect_harmony  = round(harm_ratio, 3)
        self.active_aspects  = aspects.count
        self.exact_aspects   = aspects.exact_count

        # Dignity derived
        self.exalted_planets     = dignities.exalted()
        self.debilitated_planets = dignities.debilitated()
        self.dignity_score       = round(dignities.benefic_strength(), 3)

        # Dasha
        self.dasha_benefic  = dasha.maha_dasha in NATURAL_BENEFICS
        self.dasha_planet   = dasha.maha_dasha

        # Potency — composite
        score = 0.50
        score += (harm_ratio - 0.5) * 0.20        # harmony bonus/penalty up to ±0.10
        score += (self.dignity_score - 1.0) * 0.15 # dignity bonus/penalty up to ±0.15
        score += 0.08 if self.dasha_benefic else -0.08
        score += len(self.exalted_planets)  * 0.04
        score -= len(self.debilitated_planets) * 0.04
        score += aspects.exact_count * 0.02       # exact aspects raise intensity
        self.potency = round(max(0.0, min(1.0, score)), 3)

        if self.potency >= 0.65:
            self.quality = "auspicious"
        elif self.potency <= 0.35:
            self.quality = "challenging"
        else:
            self.quality = "neutral"

        self.description = (
            f"{dasha.label()} dasha  ·  "
            f"{aspects.harmonious}H/{aspects.tense}T aspects  ·  "
            f"q:{self.quality}"
        )

    def to_dict(self) -> dict:
        return {
            "potency":              self.potency,
            "quality":              self.quality,
            "aspect_harmony":       self.aspect_harmony,
            "dignity_score":        self.dignity_score,
            "dasha_benefic":        self.dasha_benefic,
            "dasha_planet":         self.dasha_planet,
            "description":          self.description,
            "exalted_planets":      self.exalted_planets,
            "debilitated_planets":  self.debilitated_planets,
            "active_aspects":       self.active_aspects,
            "exact_aspects":        self.exact_aspects,
        }


class CaelestisTrigger:
    """Edge-event detection for astrological transitions."""
    def __init__(self):
        self._pending: list = []
        self._prev:    dict = {}

    def _edge(self, key: str, current: bool, label: str):
        if current and not self._prev.get(key, False):
            self._pending.append(label)
        self._prev[key] = current

    def _changed(self, key: str, current, label_fn):
        prev = self._prev.get(key)
        if prev is not None and prev != current:
            self._pending.append(label_fn(prev, current))
        self._prev[key] = current

    def update(self, aspects: AspectState, dignities: DignityRegistry,
               dasha: DashaState, conditions: CaelestisConditions):

        # Dasha change
        self._changed("maha_dasha", dasha.maha_dasha,
                      lambda p, c: f"maha_dasha_changed:{c}")
        self._changed("antar_dasha", dasha.antar_dasha,
                      lambda p, c: f"antar_dasha_changed:{c}")

        # Quality shift
        self._changed("quality", conditions.quality,
                      lambda p, c: f"astrological_quality_changed:{c}")

        # Exact aspects arriving
        for asp in aspects.list:
            if asp.exact:
                key = f"exact_{asp.planet_a}_{asp.planet_b}_{asp.aspect_name}"
                self._edge(key, True, f"exact_aspect:{asp.label()}")

        # Dignity transitions
        for planet, d in dignities._planets.items():
            self._changed(f"dignity_{planet}", d.status,
                          lambda p, c, pl=planet: f"dignity_changed:{pl}:{c}")

        # Exaltation / debilitation events
        self._edge("any_exalted",     len(conditions.exalted_planets) > 0,
                   "planet_exalted")
        self._edge("any_debilitated", len(conditions.debilitated_planets) > 0,
                   "planet_debilitated")

    def poll(self) -> list:
        out = list(self._pending)
        self._pending.clear()
        return out

    def peek(self) -> list:
        return list(self._pending)

    def to_dict(self) -> dict:
        return {"pending": self._pending, "history_size": len(self._prev)}


