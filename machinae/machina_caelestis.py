def _make_engines():
    try:
        from machinae.machina_horologica import MachinaHorologica
    except ImportError:
        # Allow running from the machinae/ directory directly
        sys.path.insert(0, str(Path(__file__).parent.parent))
        from machinae.machina_horologica import MachinaHorologica
    return MachinaHorologica(), MachinaCaelestis()


def run_daemon():
    sky, cael = _make_engines()
    print(f"CAELESTIS DAEMON  v{VERSION}")
    print(f"Writing to: {STATE_PATH}")
    print("Ctrl+C to stop.\n")
    try:
        while True:
            sky.update()
            cael.update(sky)
            cael.write()
            triggers = cael.triggers.poll()
            if triggers:
                ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
                for t in triggers:
                    print(f"  [{ts}] TRIGGER: {t}")
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nDaemon stopped.")


def run_once():
    sky, cael = _make_engines()
    sky.update(force=True)
    cael.update(sky, force=True)
    cael.write()
    print(cael.to_json())


def run_watch():
    sky, cael = _make_engines()
    try:
        while True:
            sky.update()
            cael.update(sky)
            cael.write()
            os.system("clear")
            print(f"  MACHINA CAELESTIS  v{VERSION}")
            print(f"  {cael.summary()}")
            print()
            print(f"  DASHA")
            print(f"    Maha:  {cael.dasha.maha_dasha:<10}"
                  f"  {cael.dasha.maha_pct*100:.1f}% elapsed"
                  f"  ({cael.dasha.maha_remaining:.2f}y remaining)")
            print(f"    Antar: {cael.dasha.antar_dasha:<10}"
                  f"  {cael.dasha.antar_pct*100:.1f}% elapsed")
            print()
            print(f"  ASPECTS  ({cael.aspects.count} active,"
                  f" {cael.aspects.harmonious}H / {cael.aspects.tense}T,"
                  f" {cael.aspects.exact_count} exact)")
            for asp in sorted(cael.aspects.list, key=lambda a: a.orb):
                marker = "◆" if asp.exact else "·"
                print(f"    {marker} {asp.label():<42}  {asp.quality}")
            print()
            print(f"  DIGNITIES")
            for planet, d in cael.dignities._planets.items():
                if planet in ("Uranus","Neptune","Pluto"): continue
                status_pad = f"{d.status:<12}"
                bar = "█" * int(d.strength * 4)
                print(f"    {planet:<10}  {status_pad}  {d.sign_name:<14}  {bar}  {d.strength:.2f}")
            print()
            print(f"  CONDITIONS")
            print(f"    potency:       {cael.conditions.potency:.3f}")
            print(f"    quality:       {cael.conditions.quality}")
            print(f"    aspect_harmony:{cael.conditions.aspect_harmony:.3f}")
            print(f"    dasha_benefic: {cael.conditions.dasha_benefic}")
            triggers = cael.triggers.poll()
            if triggers:
                print()
                print(f"  TRIGGERS")
                for t in triggers:
                    print(f"    ◆ {t}")
            time.sleep(1)
    except KeyboardInterrupt:
        print("\nWatch stopped.")


if __name__ == "__main__":
    args = sys.argv[1:]
