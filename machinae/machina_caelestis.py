class MachinaCaelestis:
    """
    Astrological interpretation engine.

    cael = MachinaCaelestis()
    sky  = MachinaHorologica()

    sky.update()
    cael.update(sky)

    cael.aspects.list                    # active aspects
    cael.dignities["Mercury"].status     # "exalted" / "own_sign" / "neutral" / etc
    cael.dasha.maha_dasha                # running major period planet
    cael.dasha.antar_dasha               # running sub-period planet
    cael.conditions.potency              # 0.0–1.0
    cael.conditions.quality              # "auspicious" / "neutral" / "challenging"
    cael.triggers.poll()                 # edge events since last poll
    """

    def __init__(self):
        self.aspects    = AspectState()
        self.dignities  = DignityRegistry()
        self.dasha      = DashaState()
        self.conditions = CaelestisConditions()
        self.triggers   = CaelestisTrigger()

        self._last_heavy = 0.0
        self._tick       = 0
        self._cycle      = 0

    def update(self, sky, force: bool = False):
        """
        Update from a live MachinaHorologica instance.
        Heavy recalculation every 60s — same cadence as Horologica.
        sky must already have had sky.update() called this tick.
        """
        self._tick += 1
        heavy = force or (time.time() - self._last_heavy >= 59)

        if heavy:
            self._cycle += 1
            self._last_heavy = time.time()

            # Collect longitudes from sky.planets
            longitudes: dict[str, float] = {}
            for name in ("Sun","Moon","Mercury","Venus","Mars","Jupiter","Saturn"):
                if name in sky.planets:
                    longitudes[name] = sky.planets[name].longitude
            # Add Rahu/Ketu from nodes
            longitudes["Rahu"] = sky.nodes.rahu_longitude
            longitudes["Ketu"] = sky.nodes.ketu_longitude

            # Collect sign indices
            planet_signs: dict[str, int] = {}
            for name in ("Sun","Moon","Mercury","Venus","Mars","Jupiter","Saturn"):
                if name in sky.planets:
                    planet_signs[name] = sky.planets[name].sign_idx
            planet_signs["Rahu"] = sky.nodes.rahu_sign_idx
            planet_signs["Ketu"] = sky.nodes.ketu_sign_idx

            self.aspects.update(longitudes)
            self.dignities.update(planet_signs)
            self.dasha.update(sky.moon.longitude)
            self.conditions.update(self.aspects, self.dignities, self.dasha)
            self.triggers.update(self.aspects, self.dignities,
                                 self.dasha, self.conditions)

    def to_dict(self) -> dict:
        return {
            "meta": {
                "ts":      datetime.now(timezone.utc).isoformat(),
                "version": VERSION,
                "cycle":   self._cycle,
                "tick":    self._tick,
            },
            "aspects":    self.aspects.to_dict(),
            "dignities":  self.dignities.to_dict(),
            "dasha":      self.dasha.to_dict(),
            "conditions": self.conditions.to_dict(),
            "triggers":   self.triggers.to_dict(),
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, default=str)

    def write(self):
        """Atomic write to ~/.arca/machina_caelestis.json"""
        ARCA_DIR.mkdir(exist_ok=True)
        tmp = ARCA_DIR / "machina_caelestis.tmp"
        with open(tmp, "w") as f:
            f.write(self.to_json())
        tmp.replace(STATE_PATH)

    def summary(self) -> str:
        return (
            f"dasha:{self.dasha.label():<22}"
            f"  q:{self.conditions.quality:<11}"
            f"  aspects:{self.aspects.count}({self.aspects.harmonious}H/{self.aspects.tense}T)"
            f"  potency:{self.conditions.potency:.2f}"
            f"  exalt:[{','.join(self.conditions.exalted_planets) or '—'}]"
            f"  debil:[{','.join(self.conditions.debilitated_planets) or '—'}]"
        )


