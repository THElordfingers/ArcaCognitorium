def _get_lon(jd: float, pid: int) -> tuple:
    """Returns (sign_idx, degree_in_sign, retrograde, absolute_lon)"""
    r = swe.calc_ut(jd, pid, swe.FLG_SIDEREAL | swe.FLG_SPEED)[0]
    return int(r[0] / 30) % 12, r[0] % 30, r[3] < 0, r[0]

def _angle_diff(a: float, b: float) -> float:
    """Shortest arc between two ecliptic longitudes."""
    diff = abs(a - b) % 360
    return diff if diff <= 180 else 360 - diff

def _dasha_balance_at_birth(moon_lon: float) -> dict:
    """
    Calculate Vimshottari dasha balance based on Moon's longitude.
    Returns current maha dasha planet + elapsed years as of J2000.0 epoch.
    This is a simplified calculation — full accuracy requires birth date.
    We use the current Moon position to infer the running dasha period.
    """
    nak_sz   = 360 / 27
    nak_i    = int(moon_lon / nak_sz) % 27
    nak_pos  = (moon_lon % nak_sz) / nak_sz  # 0.0–1.0 progress through nakshatra
    ruler    = NAKSHATRA_RULERS[nak_i]
    dasha_yrs = DASHA_YEARS[ruler]

    # Elapsed fraction of this dasha based on nakshatra traversal
    # At nakshatra entry = dasha start; at nakshatra exit = dasha end
    elapsed_fraction = nak_pos
    elapsed_years    = elapsed_fraction * dasha_yrs
    remaining_years  = dasha_yrs - elapsed_years

    return {
        "ruler":            ruler,
        "dasha_years":      dasha_yrs,
        "elapsed_years":    round(elapsed_years, 3),
        "remaining_years":  round(remaining_years, 3),
        "nakshatra_idx":    nak_i,
    }


