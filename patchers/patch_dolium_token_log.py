import sys
import shutil
from pathlib import Path

TARGET = Path.home() / "ArcaCognitorium" / "tools" / "Dolium" / "ui" / "conversation.py"
BACKUP = TARGET.with_suffix(".py.bak_token_log")

# ── Patch 1: import ───────────────────────────────────────────────────────────

OLD_IMPORT = "import threading"
NEW_IMPORT  = """\
import threading

# token_logger — cross-app usage ledger
import sys as _sys
_sys.path.insert(0, str(__import__('pathlib').Path.home() / '.arca'))
try:
    from token_logger import log_usage as _log_usage
except ImportError:
    def _log_usage(*a, **kw): pass"""

# ── Patch 2: log inside on_complete ──────────────────────────────────────────

OLD_COMPLETE = """\
        def on_complete(response) -> None:
            text = response.text if hasattr(response, 'text') else str(response)
            result.append(text or \"\")
            done.set()"""

NEW_COMPLETE  = """\
        def on_complete(response) -> None:
            text = response.text if hasattr(response, 'text') else str(response)
            result.append(text or "")
            try:
                u = response.usage
                _log_usage(
                    app="dolium",
                    model=getattr(response, "model", "unknown"),
                    input_tokens=getattr(u, "input_tokens", 0),
                    output_tokens=getattr(u, "output_tokens", 0),
                    session_id=session_id,
                )
            except Exception:
                pass
            done.set()"""

PATCHES = [
    ("Add token_logger import", OLD_IMPORT,    NEW_IMPORT),
    ("Add log_usage call",      OLD_COMPLETE,  NEW_COMPLETE),
]

def run(dry: bool) -> None:
    content = TARGET.read_text(encoding="utf-8")
    results = []
    modified = content

    for name, old, new in PATCHES:
        if old not in modified:
            results.append(f"  SKIP  {name} — already applied or not found")
        else:
            modified = modified.replace(old, new, 1)
            results.append(f"  PATCH {name}")

    print(f"Target: {TARGET}")
    for r in results: print(r)

    if dry:
        print("\n[dry run] no changes written")
        return

    if modified == content:
        print("\nNothing to apply.")
        return

    shutil.copy2(TARGET, BACKUP)
    print(f"Backup: {BACKUP}")
    TARGET.write_text(modified, encoding="utf-8")
    print("Applied.")

if __name__ == "__main__":
    run(dry="--check" in sys.argv)

